"""Prepares an APL TV version for automatic updates (the same system as APL Launcher).

Run it after every change, before publishing on GitHub:
    python tools/make-build.py --notes "what changes, in one sentence"

Writes:
  app/version.json  read by the screens (js/updater.js) to update themselves from GitHub
  app/js/build.js   what the installed version (.wgt) contains, for js/boot.js
The version comes from app/config.xml (version="..." attribute).
"""
import json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
A = os.path.join(ROOT, "app")

# Load order (boot.js loads them one by one, in this order). *.local.js are never downloaded.
SCRIPTS = [
    "js/lang-fr.js", "js/i18n.js", "js/keys.local.js", "js/dev.local.js", "js/core.js", "js/nav.js", "js/qr.js", "js/helper.js",
    "js/smart.js", "js/data.js", "js/epg.js", "js/meta.js", "js/player.js", "js/ui.js", "js/home.js", "js/live.js", "js/guide.js",
    "js/vod.js", "js/detail.js", "js/person.js", "js/search.js", "js/settings.js", "js/multiview.js", "js/osd.js", "js/voice.js",
    "js/updater.js", "js/app.js",
]
STYLES = ["css/tv.css", "css/tv2.css"]
LOADER = 1           # raise it when boot.js changes: the screens then ask for APL Launcher Setup, once
REINSTALL = "1.0.1"  # minimum installed version: raise it when config.xml or service/service.js change

def build(notes=""):
    config = open(os.path.join(A, "config.xml"), encoding="utf-8").read()
    version = re.search(r'<widget[^>]*\sversion="([^"]+)"', config).group(1)
    for s in SCRIPTS + STYLES:
        if ".local." not in s and not os.path.exists(os.path.join(A, s)):
            sys.exit("missing file: " + s)
    html = open(os.path.join(A, "index.html"), encoding="utf-8").read()
    body = html[html.index("<body"):]
    body = body[body.index(">") + 1:]
    body = body[:body.index("<!-- Samsung API")].strip()
    manifest = {"version": version, "loader": LOADER, "reinstall": REINSTALL, "notes": notes,
                "scripts": SCRIPTS, "styles": STYLES, "body": body}
    build_js = ("/* GENERATED by tools/make-build.py: contents of the installed version. */\n"
                "window.TV_BUILD = " + json.dumps({"version": version, "scripts": SCRIPTS, "styles": STYLES}, ensure_ascii=False) + ";\n")
    return version, manifest, build_js

if __name__ == "__main__":
    notes = sys.argv[sys.argv.index("--notes") + 1] if "--notes" in sys.argv else ""
    if not notes:
        try: notes = json.load(open(os.path.join(A, "version.json"), encoding="utf-8")).get("notes", "")
        except Exception: notes = ""
    version, manifest, build_js = build(notes)
    with open(os.path.join(A, "version.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=1); f.write("\n")
    with open(os.path.join(A, "js", "build.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(build_js)
    print("version", version, "-", len(SCRIPTS), "scripts,", len(STYLES), "styles")
